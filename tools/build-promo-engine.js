/* node tools/build-promo-engine.js

   Builds the promotional platform's mailer engine (promo-engine/src, TypeScript — the owner's Social Post
   Generator, ported) into one CommonJS file for Oneworld's backend: functions/lib/vendor/promo-engine.js.
   The output is committed, so App Hosting needs no build step; run this again after any change under
   promo-engine/src, and commit both. */
'use strict';
const path = require('path');
const esbuild = require('esbuild');

const ROOT = path.resolve(__dirname, '..');
esbuild.build({
  entryPoints: [path.join(ROOT, 'promo-engine', 'src', 'index.ts')],
  outfile: path.join(ROOT, 'functions', 'lib', 'vendor', 'promo-engine.js'),
  bundle: true,
  platform: 'node',
  format: 'cjs',
  target: 'node20',
  legalComments: 'none',
  banner: { js: '/* GENERATED by tools/build-promo-engine.js from promo-engine/src — do not edit; edit the source and rebuild. */' },
  logLevel: 'warning'
}).then(function (r) {
  if (r.warnings.length) console.warn(r.warnings.length + ' warning(s)');
  console.log('Built functions/lib/vendor/promo-engine.js');
}, function (err) { console.error(err && err.message || err); process.exit(1); });

/** The exact copy of a stock html-to-image.js text: a header, then the stock text without FRAGMENT. Throws unless
 *  FRAGMENT is in it exactly once. */
function exactCopy(stock) {
  const n = String(stock).split(FRAGMENT).length - 1;
  if (n !== 1) {
    throw new Error('html-to-image-exact: the font-size floor was found ' + n + ' time(s) in the stock html-to-image.js, not once. ' +
      'The stock file has changed: check what it does with font sizes now, then update FRAGMENT in tools/build-promo-social.js.');
  }
  const header = '/* GENERATED by tools/build-promo-social.js from assets/vendor/html-to-image.js — do not edit; rebuild.\n' +
    '   html-to-image ' + H2I_VERSION + ' (https://github.com/bubkoo/html-to-image), the stock file byte for byte except one fragment\n' +
    '   taken out: the font-size floor in its computed-style copy, which rounded every px font size down and took 0.1 px off.\n' +
    '   With it, posts drew smaller than Chrome lays them out and lines rewrapped; without it they match the platform\'s\n' +
    '   screenshots. Used by Promotions → Social posts only. Stock file sha256 ' + sha256(stock) + '.\n\n' +
    H2I_LICENSE.map(function (l) { return ('   ' + l).replace(/\s+$/, ''); }).join('\n') + '\n*/\n';
  return header + String(stock).replace(FRAGMENT, '');
}

const LICENSE_WEBTOON = path.join(ROOT, 'promo-engine', 'vendor', 'webtoon-psd', 'LICENSE');

/** The OWSocial bundle's text. */
function buildBundle() {
  const esbuild = require('esbuild');
  const pkg = JSON.parse(fs.readFileSync(path.join(ROOT, 'promo-engine', 'vendor', 'webtoon-psd', 'package.json'), 'utf8'));
  // MIT asks for its notice in every copy; the bundle is the copy browsers get
  const licence = fs.readFileSync(LICENSE_WEBTOON, 'utf8').trim().split(/\r?\n/).map(function (l) { return ('   ' + l).replace(/\s+$/, ''); }).join('\n');
  const banner = '/* GENERATED by tools/build-promo-social.js from promo-engine/src/browser.ts — do not edit; edit the source and rebuild.\n' +
    '   window.OWSocial for Promotions → Social posts: extract, renderEditableHtml, psdUnits, classify, MAX_EDGE, PSD_LIMITS.\n' +
    '   It includes ' + pkg.name + ' ' + pkg.version + ' (promo-engine/vendor/webtoon-psd), under the ' + pkg.license + ' licence:\n\n' +
    licence + '\n*/';
  return esbuild.build({
    // file names in the bundle's comments are relative to the repo, whatever folder the build is started from
    absWorkingDir: ROOT,
    entryPoints: [ENTRY],
    bundle: true,
    format: 'iife',
    globalName: 'OWSocial',
    platform: 'browser',
    target: 'es2018',
    legalComments: 'none',
    banner: { js: banner },
    write: false,
    logLevel: 'silent'
  }).then(function (r) {
    if (r.warnings.length) {
      throw new Error('promo-social: esbuild warned — ' + r.warnings.map(function (w) { return w.text + (w.location ? ' (' + w.location.file + ':' + w.location.line + ')' : ''); }).join('; '));
    }
    return r.outputFiles[0].text;
  });
}

/** Both outputs, in memory: { bundle, exact }. Nothing is written. */
function buildAll() {
  return Promise.resolve().then(function () {
    const exact = exactCopy(fs.readFileSync(STOCK, 'utf8'));
    return buildBundle().then(function (bundle) { return { bundle: bundle, exact: exact }; });
  });
}

if (require.main === module) {
  const check = process.argv.indexOf('--check') !== -1;
  buildAll().then(function (out) {
    const rel = function (p) { return path.relative(ROOT, p); };
    if (check) {
      const stale = Object.keys(OUT).filter(function (k) {
        return !fs.existsSync(OUT[k]) || fs.readFileSync(OUT[k], 'utf8') !== out[k];
      });
      if (stale.length) { console.error('Out of date: ' + stale.map(function (k) { return rel(OUT[k]); }).join(', ') + ' — run node tools/build-promo-social.js'); process.exit(1); }
      console.log('Up to date: ' + rel(OUT.bundle) + ', ' + rel(OUT.exact));
      return;
    }
    // both are built before either is written, so a failed build leaves the committed pair as it was
    fs.writeFileSync(OUT.bundle, out.bundle);
    fs.writeFileSync(OUT.exact, out.exact);
    console.log('Built ' + rel(OUT.bundle) + ' (' + out.bundle.length + ' bytes) and ' + rel(OUT.exact) + ' (' + out.exact.length + ' bytes)');
  }, function (err) { console.error(err && err.message || err); process.exit(1); });
}

module.exports = { FRAGMENT: FRAGMENT, exactCopy: exactCopy, buildBundle: buildBundle, buildAll: buildAll, OUT: OUT, STOCK: STOCK, H2I_VERSION: H2I_VERSION };

/* node tools/build-promo-social.js [--check]

   Builds the two browser files of Promotions → Social posts (promo-social-studio.html loads both):

   1. assets/vendor/promo-social.js — the platform's social posts engine, browser half (promo-engine/src/browser.ts:
      the editor's flattener, its export page and the PSD reader, with @webtoon/psd from promo-engine/vendor), as one
      IIFE that sets window.OWSocial.
   2. assets/vendor/html-to-image-exact.js — the stock assets/vendor/html-to-image.js with one fragment taken out: its
      font-size floor, which rounds every font size down and takes 0.1 px off. Posts drawn with the stock file come
      out with smaller text and lines that wrap differently from the platform's Chrome screenshots; without the
      fragment all 72 probe renders (9 templates × 4 sizes × 2) match. The stock file is left as it is: Site-look
      posts and the mailer export use it. The build stops, writing nothing, unless the fragment is found exactly
      once, so a new stock file is never patched blindly.

   Both outputs are committed, so App Hosting needs no build step. Run this again after any change under
   promo-engine/src that browser.ts reaches, in promo-engine/vendor/webtoon-psd or in the stock html-to-image.js, and
   commit the outputs. The same inputs always give the same bytes. --check builds in memory and exits 1 when a
   committed output differs from what the sources give now (nothing is written).

   Required as a module it builds nothing and exports { FRAGMENT, exactCopy, buildBundle, buildAll, OUT, STOCK,
   H2I_VERSION }, for functions/lib/promo-social-browser.test.js. */
'use strict';
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const ROOT = path.resolve(__dirname, '..');
const ENTRY = path.join(ROOT, 'promo-engine', 'src', 'browser.ts');
const STOCK = path.join(ROOT, 'assets', 'vendor', 'html-to-image.js');
const OUT = {
  bundle: path.join(ROOT, 'assets', 'vendor', 'promo-social.js'),
  exact: path.join(ROOT, 'assets', 'vendor', 'html-to-image-exact.js'),
};

/* The font-size floor, as html-to-image writes it when it copies each computed style onto its clone (the stock
   file's own text, found exactly once there). */
const FRAGMENT = 'if("font-size"===n&&o.endsWith("px")){var u=Math.floor(parseFloat(o.substring(0,o.length-2)))-.1;o="".concat(u,"px")}';

const sha256 = (s) => crypto.createHash('sha256').update(s).digest('hex');


import type {
  InfographicCategory,
  InfographicData,
  InfographicItem,
  InfographicTemplate,
  InfographicVisualVariant,
} from '../types/bookstudio';

interface TemplateSeed {
  id: string;
  name: string;
  category: InfographicCategory;
  variant: InfographicVisualVariant;
  description: string;
  tags: string[];
  title: string;
  subtitle: string;
  accent: string;
  secondary: string;
  bg?: string;
  ink?: string;
  items: InfographicItem[];
}

function makeTemplate(seed: TemplateSeed): InfographicTemplate {
  const defaultData: InfographicData = {
    templateId: seed.id,
    variant: seed.variant,
    title: seed.title,
    subtitle: seed.subtitle,
    categoryLabel: seed.category,
    sourceNote: 'Editorial Data · Editable in BOOKSTUDIO',
    fontFamily: 'Plus Jakarta Sans',
    backgroundColor: seed.bg || '#F7F4EE',
    textColor: seed.ink || '#1C1917',
    accentColor: seed.accent,
    secondaryColor: seed.secondary,
    items: seed.items,
    showLegend: true,
    showValues: true,
  };
  return {
    id: seed.id,
    name: seed.name,
    category: seed.category,
    variant: seed.variant,
    description: seed.description,
    tags: seed.tags,
    defaultWidthMm: 184,
    defaultHeightMm: 118,
    defaultData,
  };
}


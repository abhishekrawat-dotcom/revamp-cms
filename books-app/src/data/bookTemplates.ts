function buildDesignSystem(spec: BookTemplateSpec): DesignSystem {
  return {
    name: `${spec.name} Design System`,
    approved: true,
    sourceTemplateName: spec.name,
    colors: {
      paper: spec.paper,
      surface: spec.surface,
      ink: spec.ink,
      mutedInk: spec.mutedInk,
      primaryAccent: spec.accent,
      secondaryAccent: spec.secondaryAccent,
      palette: [
        spec.paper,
        spec.surface,
        spec.ink,
        spec.mutedInk,
        spec.accent,
        spec.secondaryAccent,
      ],
    },
    typography: {
      primaryFont: spec.displayFont,
      secondaryFont: spec.captionFont,
      displayFont: spec.displayFont,
      headingFont: spec.headingFont,
      bodyFont: spec.bodyFont,
      captionFont: spec.captionFont,
      quoteFont: spec.quoteFont,
      numericalFont: spec.numericalFont,
      scale: {
        displayPt: 38,
        headingPt: 22,
        subheadingPt: 13,
        bodyPt: 10.5,
        captionPt: 8.5,
        quotePt: 18,
        folioPt: 8.5,
      },
      minApprovedBodyPt: 8.5,
    },
    spacing: {
      baselineMm: 4.5,
      paragraphGapMm: 4,
      sectionGapMm: 10,
      imageCaptionGapMm: 4,
    },
    grid: {
      columns: 2,
      gutterMm: 8,
      margins: { top: 20, bottom: 22, inner: 24, outer: 18 },
    },
  };
}

function buildDimensions(spec: BookTemplateSpec): PageDimensions {
  const orientation =
    Math.abs(spec.widthMm - spec.heightMm) <= 2
      ? 'square'
      : spec.widthMm > spec.heightMm
        ? 'landscape'
        : 'portrait';
  return {
    widthMm: spec.widthMm,
    heightMm: spec.heightMm,
    orientation,
    rotation: 0,
    margins: { top: 20, bottom: 22, inner: 24, outer: 18 },
    gutterMm: 8,
    bleedMm: 3,
    safeAreaMm: 10,
    columns: 2,
    columnGapMm: 8,
    baselineGridMm: 4.5,
    spreadMode: 'facing',
    presetName:
      orientation === 'square'
        ? 'Square Art Monograph'
        : orientation === 'landscape'
          ? 'Landscape Coffee Table Book'
          : 'Portrait Coffee Table Book',
  };
}

